/* Original squid sprites, expanded 3x into opaque or transparent A8 pixels in flash. */
#define PIXEL(bits, bit) (((bits) & (1u << (bit))) ? 255 : 0)
#define TRIPLE(bits, bit) PIXEL(bits, bit), PIXEL(bits, bit), PIXEL(bits, bit)
#define BYTE(bits) TRIPLE(bits, 7), TRIPLE(bits, 6), TRIPLE(bits, 5), TRIPLE(bits, 4), \
                   TRIPLE(bits, 3), TRIPLE(bits, 2), TRIPLE(bits, 1), TRIPLE(bits, 0)
#define ROW(left, right) BYTE(left), BYTE(right), BYTE(left), BYTE(right), BYTE(left), BYTE(right)

