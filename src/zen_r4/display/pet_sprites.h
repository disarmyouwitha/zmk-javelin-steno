/* Pop squid, hand-pixelled on a 24 x 24 grid and expanded 2x to 48 x 48.
 * Black/transparent pixels only; the sprite footprint and animation API are unchanged.
 */
#define PIXEL(bits, bit) (((bits) & (1u << (bit))) ? 255 : 0)
#define PAIR(bits, bit) PIXEL(bits, bit), PIXEL(bits, bit)
#define LINE(bits) PAIR(bits, 23), PAIR(bits, 22), PAIR(bits, 21), PAIR(bits, 20), \
                   PAIR(bits, 19), PAIR(bits, 18), PAIR(bits, 17), PAIR(bits, 16), \
                   PAIR(bits, 15), PAIR(bits, 14), PAIR(bits, 13), PAIR(bits, 12), \
                   PAIR(bits, 11), PAIR(bits, 10), PAIR(bits, 9), PAIR(bits, 8), \
                   PAIR(bits, 7), PAIR(bits, 6), PAIR(bits, 5), PAIR(bits, 4), \
                   PAIR(bits, 3), PAIR(bits, 2), PAIR(bits, 1), PAIR(bits, 0)
#define ROW(bits) LINE(bits), LINE(bits)

